#!/usr/bin/php
<?php
/**
 * Root-owned privileged helper for the panel's Asterisk Configuration
 * module. This is the ONLY piece of the module that runs as root, and it
 * is invoked ONLY via a fixed, argument-less sudoers NOPASSWD rule for
 * this exact absolute path (see asterisk/bin/install-asterisk-config-module.sh).
 *
 * It never reads argv or the environment for instructions — the job to
 * perform is read from a fixed staging file that only the web app
 * (www-data) can write, and the two actions below are the entire
 * allowlist: write a validated managed-block replacement into the live
 * PJSIP/dialplan/RTP config files (after backing them up), or restore a
 * previous backup. Everything else — reload commands, status checks,
 * validation — happens as www-data in Laravel, which already has group
 * read/write on the Asterisk control socket and needs no elevation.
 *
 * Keep this script's privileged surface as small as possible: it does
 * file I/O only and never shells out to Asterisk or anything else.
 */

const STAGING_DIR   = '/var/lib/6g-asterisk-config/staging';
const BACKUPS_DIR   = '/var/lib/6g-asterisk-config/backups';
const PJSIP_CONF    = '/etc/asterisk/pjsip.conf';
const EXTENSIONS_CONF = '/etc/asterisk/extensions.conf';
const RTP_CONF      = '/etc/asterisk/rtp.conf';

// Must match AsteriskConfigGenerator::PJSIP_BEGIN/END exactly — these are
// also the same markers asterisk/bin/pjsip_generate.php already uses in
// the live pjsip.conf, so this replaces that block instead of duplicating it.
const PJSIP_BEGIN = '; === BEGIN MANAGED TRUNKS - generated, do not edit ===';
const PJSIP_END   = '; === END MANAGED TRUNKS ===';
const DIALPLAN_BEGIN = '; === BEGIN MANAGED DIALPLAN - generated by Asterisk Configuration module, do not edit ===';
const DIALPLAN_END   = '; === END MANAGED DIALPLAN ===';

function fail(string $msg): void
{
    fwrite(STDERR, $msg."\n");
    echo json_encode(['success' => false, 'error' => $msg])."\n";
    exit(1);
}

function spliceManagedBlock(string $live, string $begin, string $end, string $managed): string
{
    $b = strpos($live, $begin);
    $e = strpos($live, $end);
    if ($b !== false && $e !== false && $e > $b) {
        $head = substr($live, 0, $b);
        $tail = substr($live, $e + strlen($end));
        return rtrim($head)."\n\n".rtrim($managed)."\n".ltrim($tail, "\n");
    }
    // First run: no markers yet, append at the end.
    return rtrim($live)."\n\n".rtrim($managed)."\n";
}

if (posix_getuid() !== 0) {
    fail('must run as root');
}

if (!is_dir(STAGING_DIR)) {
    fail('staging dir missing: '.STAGING_DIR);
}

$jobPath = STAGING_DIR.'/job.json';
$raw = @file_get_contents($jobPath);
if ($raw === false) {
    fail('no job file at '.$jobPath);
}
$job = json_decode($raw, true);
if (!is_array($job) || empty($job['action'])) {
    fail('invalid job payload');
}

@unlink($jobPath); // one-shot — never re-run a stale job

if (!is_dir(BACKUPS_DIR)) {
    @mkdir(BACKUPS_DIR, 0750, true);
}

switch ($job['action']) {
    case 'write':
        $backupId = date('Ymd-His');
        $backupDir = BACKUPS_DIR.'/'.$backupId;
        mkdir($backupDir, 0750, true);

        foreach (['pjsip.conf' => PJSIP_CONF, 'extensions.conf' => EXTENSIONS_CONF, 'rtp.conf' => RTP_CONF] as $name => $path) {
            if (is_file($path)) {
                copy($path, $backupDir.'/'.$name);
            }
        }
        chown($backupDir, 'www-data');
        chgrp($backupDir, 'www-data');
        foreach (glob($backupDir.'/*') as $f) {
            chown($f, 'www-data');
            chgrp($f, 'www-data');
            chmod($f, 0640);
        }

        if (isset($job['pjsip_managed'])) {
            $live = is_file(PJSIP_CONF) ? file_get_contents(PJSIP_CONF) : '';
            file_put_contents(PJSIP_CONF.'.tmp', spliceManagedBlock($live, PJSIP_BEGIN, PJSIP_END, $job['pjsip_managed']));
            rename(PJSIP_CONF.'.tmp', PJSIP_CONF);
            chown(PJSIP_CONF, 'asterisk');
            chgrp(PJSIP_CONF, 'asterisk');
            chmod(PJSIP_CONF, 0640);
        }

        if (isset($job['dialplan_managed'])) {
            $live = is_file(EXTENSIONS_CONF) ? file_get_contents(EXTENSIONS_CONF) : '';
            file_put_contents(EXTENSIONS_CONF.'.tmp', spliceManagedBlock($live, DIALPLAN_BEGIN, DIALPLAN_END, $job['dialplan_managed']));
            rename(EXTENSIONS_CONF.'.tmp', EXTENSIONS_CONF);
            chown(EXTENSIONS_CONF, 'asterisk');
            chgrp(EXTENSIONS_CONF, 'asterisk');
            chmod(EXTENSIONS_CONF, 0640);
        }

        if (isset($job['rtp_start'], $job['rtp_end']) && is_file(RTP_CONF)) {
            $rtp = file_get_contents(RTP_CONF);
            $rtp = preg_replace('/^rtpstart=\d+/m', 'rtpstart='.(int) $job['rtp_start'], $rtp, 1);
            $rtp = preg_replace('/^rtpend=\d+/m', 'rtpend='.(int) $job['rtp_end'], $rtp, 1);
            file_put_contents(RTP_CONF.'.tmp', $rtp);
            rename(RTP_CONF.'.tmp', RTP_CONF);
            chown(RTP_CONF, 'asterisk');
            chgrp(RTP_CONF, 'asterisk');
            chmod(RTP_CONF, 0640);
        }

        echo json_encode(['success' => true, 'backup_id' => $backupId])."\n";
        break;

    case 'restore':
        $backupId = preg_replace('/[^0-9A-Za-z_-]/', '', (string) ($job['backup_id'] ?? ''));
        $backupDir = BACKUPS_DIR.'/'.$backupId;
        if ($backupId === '' || !is_dir($backupDir)) {
            fail('backup not found: '.$backupId);
        }

        // Snapshot current (pre-rollback) state first so a rollback is itself reversible.
        $safetyId = date('Ymd-His').'-prerollback';
        $safetyDir = BACKUPS_DIR.'/'.$safetyId;
        mkdir($safetyDir, 0750, true);
        foreach (['pjsip.conf' => PJSIP_CONF, 'extensions.conf' => EXTENSIONS_CONF, 'rtp.conf' => RTP_CONF] as $name => $path) {
            if (is_file($path)) {
                copy($path, $safetyDir.'/'.$name);
            }
        }
        chown($safetyDir, 'www-data');
        chgrp($safetyDir, 'www-data');

        foreach (['pjsip.conf' => PJSIP_CONF, 'extensions.conf' => EXTENSIONS_CONF, 'rtp.conf' => RTP_CONF] as $name => $livePath) {
            $backupFile = $backupDir.'/'.$name;
            if (is_file($backupFile)) {
                copy($backupFile, $livePath.'.tmp');
                rename($livePath.'.tmp', $livePath);
                chown($livePath, 'asterisk');
                chgrp($livePath, 'asterisk');
                chmod($livePath, 0640);
            }
        }

        echo json_encode(['success' => true, 'restored_from' => $backupId, 'safety_backup_id' => $safetyId])."\n";
        break;

    default:
        fail('unknown action: '.$job['action']);
}
